import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {gzipSync} from 'node:zlib';
const root=path.resolve('dist'),base='/vernier-caliper/';
async function walk(dir){const out=[];for(const item of await fs.readdir(dir,{withFileTypes:true})){const full=path.join(dir,item.name);if(item.isDirectory())out.push(...await walk(full));else out.push(full);}return out;}
const source=(await walk(root)).filter(f=>!f.endsWith('.map')&&!path.basename(f).startsWith('.')&&!['sw.js','offline-manifest.json','build-metrics.json'].includes(path.basename(f)));
const files=[];let gzipped=0;
for(const file of source.sort()){const bytes=await fs.readFile(file);gzipped+=gzipSync(bytes).length;files.push({url:base+path.relative(root,file).replaceAll(path.sep,'/'),bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex')});}
const version=crypto.createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0,16),cache=`precision-lab-${version}`;
const manifest={version,cache,base,bytes:files.reduce((n,f)=>n+f.bytes,0),gzipBytes:gzipped,files};
await fs.writeFile(path.join(root,'offline-manifest.json'),JSON.stringify(manifest,null,2));
const sw=`/* Generated by scripts/offline-build.mjs. Local assets only. */
const CACHE=${JSON.stringify(cache)};
const BASE=${JSON.stringify(base)};
const FILES=${JSON.stringify(files)};
const MARKER=BASE+'offline-ready';
const MANIFEST=BASE+'offline-manifest.json';
const KNOWN=new Set(FILES.map(f=>f.url));
self.addEventListener('install',event=>event.waitUntil((async()=>{const c=await caches.open(CACHE);await c.addAll([BASE+'index.html',BASE+'icon.svg',BASE+'manifest.webmanifest',MANIFEST]);})()));
self.addEventListener('activate',event=>event.waitUntil(self.clients.claim()));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);if(url.origin!==self.location.origin||event.request.method!=='GET'||!url.pathname.startsWith(BASE))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);const key=event.request.mode==='navigate'?BASE+'index.html':url.pathname;
    const cached=await cache.match(key);if(cached)return cached;
    const old=await caches.match(key);if(old)return old;
    const response=await fetch(event.request);if(response.ok&&(KNOWN.has(key)||key===MANIFEST))await cache.put(key,response.clone());return response;
  })());
});
self.addEventListener('message',event=>{
  if(event.data?.type==='ACTIVATE_UPDATE'){event.waitUntil(self.skipWaiting());return;}
  if(event.data?.type!=='MAKE_OFFLINE')return;const port=event.ports[0];
  event.waitUntil((async()=>{let done=0;const total=FILES.length;try{
    const cache=await caches.open(CACHE);await cache.delete(MARKER);
    for(const file of FILES){
      port.postMessage({status:'working',done,total,message:'Verifying the complete offline course…'});
      let response=await cache.match(file.url);if(!response)response=await fetch(file.url,{cache:'reload'});
      if(!response.ok)throw new Error('An offline asset could not be downloaded ('+file.url+'). Retry when the connection is available.');
      const bytes=await response.clone().arrayBuffer();const digest=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes))).map(b=>b.toString(16).padStart(2,'0')).join('');
      if(digest!==file.sha256){response=await fetch(file.url,{cache:'reload'});const fresh=await response.clone().arrayBuffer();const hash=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',fresh))).map(b=>b.toString(16).padStart(2,'0')).join('');if(!response.ok||hash!==file.sha256)throw new Error('An asset version changed ('+file.url+'; '+CACHE+'). Save your work, apply any pending update, reload the course, and retry.');}
      await cache.put(file.url,response);done++;
    }
    const checks=await Promise.all(FILES.map(file=>cache.match(file.url)));if(checks.some(v=>!v))throw new Error('The browser could not retain every course asset.');
    const manifestResponse=await fetch(MANIFEST,{cache:'reload'});if(!manifestResponse.ok)throw new Error('The offline manifest could not be verified. Retry when the connection is available.');await cache.put(MANIFEST,manifestResponse);await cache.put(MARKER,new Response(JSON.stringify({version:CACHE,files:total}),{headers:{'Content-Type':'application/json'}}));
    port.postMessage({status:'ready',done,total,message:'Offline ready. Every course asset has been downloaded and verified.'});
  }catch(error){port.postMessage({status:'error',done,total,message:error?.message||'Offline storage is unavailable. The online lab still works.'});}})());
});
`;
await fs.writeFile(path.join(root,'sw.js'),sw);
await fs.writeFile(path.join(root,'build-metrics.json'),JSON.stringify({version,totalRuntimeBytes:manifest.bytes,totalRuntimeGzipBytes:gzipped,sourceMapsExcludedFromOffline:true,offlineBudgetBytes:20*1024*1024,withinOfflineBudget:manifest.bytes<20*1024*1024},null,2));
console.log(`Offline manifest: ${files.length} files, ${manifest.bytes} bytes (${gzipped} gzip), build ${version}`);
